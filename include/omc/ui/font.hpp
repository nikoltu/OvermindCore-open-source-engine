inline const uint8_t* font_glyph(char ch) {
    unsigned u = static_cast<unsigned char>(ch);
    if (u < static_cast<unsigned>(kFontFirst) || u > static_cast<unsigned>(kFontLast))
        u = static_cast<unsigned>(kFontFirst);
    return kFontGlyphs[u - kFontFirst];
}

inline bool font_pixel(char ch, int col, int row) {
    if (col < 0 || col >= kFontW || row < 0 || row >= kFontH) return false;
    return (font_glyph(ch)[row] >> (kFontW - 1 - col)) & 1u;
}

